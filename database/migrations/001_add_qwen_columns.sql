-- Purpose: Add confidence score, reasoning, and extraction timestamp for Qwen AI classifications
-- Idempotent: Safe to run multiple times using INFORMATION_SCHEMA checks

-- Use the newipcsistemas database
USE `novos_sistemas_ipc`;

-- ============================================================================
-- HELPER: Add confidence column if it doesn't exist
-- ============================================================================
DELIMITER //

DROP PROCEDURE IF EXISTS add_confidence_column //

CREATE PROCEDURE add_confidence_column()
BEGIN
  DECLARE col_exists INT DEFAULT 0;

  SELECT COUNT(*) INTO col_exists
  FROM INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = 'novos_sistemas_ipc'
  AND TABLE_NAME = 'communications'
  AND COLUMN_NAME = 'confidence';

  IF col_exists = 0 THEN
    ALTER TABLE `communications`
    ADD COLUMN `confidence` FLOAT NULL DEFAULT NULL
    COMMENT 'Classification confidence score from Qwen (0.0-1.0)';
    SELECT 'Column confidence added successfully' AS status;
  ELSE
    SELECT 'Column confidence already exists, skipping' AS status;
  END IF;
END //

