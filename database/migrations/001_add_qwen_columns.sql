-- ============================================================================
-- HELPER: Create index on confidence if it doesn't exist
-- ============================================================================

DROP PROCEDURE IF EXISTS add_confidence_index //

CREATE PROCEDURE add_confidence_index()
BEGIN
  DECLARE idx_exists INT DEFAULT 0;

  SELECT COUNT(*) INTO idx_exists
  FROM INFORMATION_SCHEMA.STATISTICS
  WHERE TABLE_SCHEMA = 'novos_sistemas_ipc'
  AND TABLE_NAME = 'communications'
  AND INDEX_NAME = 'idx_confidence';

  IF idx_exists = 0 THEN
    CREATE INDEX `idx_confidence` ON `communications` (`confidence`);
    SELECT 'Index idx_confidence created successfully' AS status;
  ELSE
    SELECT 'Index idx_confidence already exists, skipping' AS status;
  END IF;
END //

